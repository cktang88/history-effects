import { Handle, Position, type NodeProps } from "@xyflow/react";
import { dateOf } from "../types";
import { expand } from "../graph/actions";
import { KIND_LABEL } from "../graph/atlasActions";
import { useGraph } from "../graph/store";
import type { EventNodeType } from "../graph/model";

const JOB_TEXT = {
  explore: "Reading the history…",
  effects: "Tracing what it led to…",
  causes: "Tracing what led to it…",
  more: "Looking for more…",
  enrich: "Checking sources…",
  path: "Connecting…",
  explain: "Explaining…",
} as const;

export function EventNode({ id, data }: NodeProps<EventNodeType>) {
  const job = useGraph((s) => s.jobs[id]);
  const selected = useGraph((s) => s.selection?.type === "node" && s.selection.id === id);
  const focus = useGraph((s) => (s.focus ? (s.focus.nodes.has(id) ? "lit" : "dim") : "none"));
  const countIn = useGraph((s) => s.edges.reduce((k, e) => k + (e.target === id ? 1 : 0), 0));
  const countOut = useGraph((s) => s.edges.reduce((k, e) => k + (e.source === id ? 1 : 0), 0));
  const pending = job?.kind === "explore" && !data.description;

  const grow = (direction: "effects" | "causes") => (e: React.MouseEvent) => {
    e.stopPropagation();
    void expand(id, direction);
  };

  return (
    <div
      className={`card domain-${data.domain ?? "none"} focus-${focus}${selected ? " is-selected" : ""}${job ? " is-busy" : ""}`}
    >
      <Handle type="target" position={Position.Left} className="handle handle-in" />
      <GrowButton side="in" onMap={countIn} available={data.nCauses} busy={!!job} onClick={grow("causes")} />

      <div className="card-meta">
        <span className="card-dot" />
        <span className="card-domain">{data.kind ? (KIND_LABEL[data.kind] ?? data.kind) : (data.domain ?? (pending ? "" : "event"))}</span>
        {data.source === "ai" && <span className="card-ai" title="Generated by the AI model, not from the curated database">AI</span>}
        <span className="card-date">{dateOf(data)}</span>
        {data.verified && <span className="card-verified" title="Checked against web sources">✓</span>}
      </div>
      <div className="card-title">{data.title}</div>
      {pending ? (
        <div className="skeleton">
          <span />
          <span />
          <span />
        </div>
      ) : job ? null : (
        <div className="card-desc">{data.description}</div>
      )}
      {job && !pending && (
        <div className="card-status">
          <span className="spinner" />
          <span className="card-status-text">{JOB_TEXT[job.kind]}</span>
        </div>
      )}

      <GrowButton side="out" onMap={countOut} available={data.nEffects} busy={!!job} onClick={grow("effects")} />
      <Handle type="source" position={Position.Right} className="handle handle-out" />
    </div>
  );
}

// Shows how many sourced links are still unexplored ("+3"), or how many are
// already on the map once everything is out.
function GrowButton(props: { side: "in" | "out"; onMap: number; available?: number; busy: boolean; onClick: (e: React.MouseEvent) => void }) {
  const remaining = Math.max(0, (props.available ?? 0) - props.onMap);
  const what = props.side === "in" ? "causes" : "effects";
  const title =
    remaining > 0
      ? `${remaining} more sourced ${what} (${props.side === "in" ? "C" : "E"})`
      : props.side === "in"
        ? "What caused this? (C)"
        : "What did this lead to? (E)";
  return (
    <button className={`grow grow-${props.side}${remaining > 0 ? " has-more" : ""}`} title={title} onClick={props.onClick} disabled={props.busy}>
      {remaining > 0 ? <span className="grow-count">+{remaining}</span> : props.onMap > 0 ? <span className="grow-count">{props.onMap}</span> : "+"}
    </button>
  );
}
